let currentLanguage = "en";

export function t(key, values = {}) {
    const template = messages[currentLanguage][key] || messages.en[key] || key;
    return template.replace(/\{\{(\w+)\}\}/g, function (match, name) {
        return Object.prototype.hasOwnProperty.call(values, name) ? values[name] : match;
    });
}

function applyTranslations() {
    document.documentElement.lang = currentLanguage;
    document.querySelectorAll("[data-i18n]").forEach(function (element) {
        element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {
        element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(function (element) {
        element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
    const title = document.querySelector("title[data-i18n]");
    if (title) {
        document.title = title.textContent;
    }
}

export function initializeLanguage() {
    try {
        const savedLanguage = window.localStorage.getItem("coderun-language");
        currentLanguage = savedLanguage === "ru" ? "ru" : "en";
    } catch (error) {
        currentLanguage = "en";
    }

    window.coderunT = t;
    applyTranslations();
    const toggle = document.getElementById("languageToggle");
    if (toggle) {
        toggle.addEventListener("click", function () {
            currentLanguage = currentLanguage === "en" ? "ru" : "en";
            try {
                window.localStorage.setItem("coderun-language", currentLanguage);
            } catch (error) {
            }
            applyTranslations();
            window.dispatchEvent(new CustomEvent("coderun:languagechange", { detail: { language: currentLanguage } }));
        });
    }
}

export function getCurrentLanguage() {
    return currentLanguage;
}
